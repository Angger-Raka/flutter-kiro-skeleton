import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import '../../tool/generate_tokens.dart';

void main() {
  late Directory dir;
  setUp(() => dir = Directory.systemTemp.createTempSync('determinism_'));
  tearDown(() => dir.deleteSync(recursive: true));

  Future<List<int>> generate(String name) async {
    final out = '${dir.path}/$name.dart';
    final code = await runGenerator(
      yamlPath: defaultYamlPath,
      outputPath: out,
      stdout: StringBuffer(),
    );
    expect(code, 0);
    return File(out).readAsBytesSync();
  }

  test('two runs give byte-identical files', () async {
    expect(await generate('a'), await generate('b'));
  });

  test('the committed tokens.g.dart equals a fresh run', () async {
    final fresh = await generate('fresh');
    expect(File(defaultOutputPath).readAsBytesSync(), fresh);
  });

  test('the committed file is marked generated and is tracked', () {
    expect(
      File(defaultOutputPath).readAsStringSync(),
      startsWith('// GENERATED by tool/generate_tokens.dart'),
    );
    final r = Process.runSync('git', ['ls-files', defaultOutputPath]);
    expect((r.stdout as String).trim(), defaultOutputPath);
  });
}
