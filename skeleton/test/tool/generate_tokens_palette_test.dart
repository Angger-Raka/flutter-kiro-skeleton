import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import '../../tool/generate_tokens.dart';
import '../../tool/src/color_math.dart';
import '../../tool/src/knobs.dart';
import '../../tool/src/palette.dart';

void main() {
  late Directory dir;
  late String source;

  setUp(() async {
    // Inside the package (build/ is ignored) so `dart analyze` resolves
    // package:flutter.
    Directory('build').createSync(recursive: true);
    dir = Directory('build').createTempSync('tokens_palette_');
    final out = File('${dir.path}/tokens_out.dart');
    final code = await runGenerator(
      yamlPath: defaultYamlPath,
      outputPath: out.path,
      stdout: StringBuffer(),
    );
    expect(code, 0);
    source = out.readAsStringSync();
  });

  tearDown(() => dir.deleteSync(recursive: true));

  test('output is marked generated and has the palette shapes', () {
    expect(source, startsWith('// GENERATED by tool/generate_tokens.dart'));
    expect(source, contains('class AppPalette'));
    expect(source, contains('static const AppPalette light'));
    expect(source, contains('static const AppPalette dark'));
    expect(source, contains('class HueScale'));
    expect(RegExp(r'HueRole\.\w+: HueScale').allMatches(source), hasLength(10));
    for (final role in hueRoleNames) {
      expect('HueRole.$role: HueScale'.allMatches(source), hasLength(2));
    }
    expect('identity: <HueScale>[]'.allMatches(source), hasLength(2));
  });

  test('output is valid Dart (no analyzer errors)', () {
    final result = Process.runSync('dart', [
      'analyze',
      '${dir.path}/tokens_out.dart',
    ]);
    expect(
      result.stdout,
      isNot(contains('error •')),
      reason: '${result.stdout}',
    );
    expect(result.exitCode, anyOf(0, 1)); // infos/warnings only
  });

  test('derived values follow 04 §4.2 / §4.4', () {
    final knobs = Knobs.parse(File(defaultYamlPath).readAsStringSync());
    final light = buildPalette(
      knobs,
      dark: false,
      ink: baseInk(knobs, dark: false),
    );
    final dark = buildPalette(
      knobs,
      dark: true,
      ink: baseInk(knobs, dark: true),
    );
    expect(toHex(light.ground), '#f9f9f8'); // ink-2
    expect(toHex(light.panel), '#ffffff');
    expect(toHex(light.well), '#f1f0ef'); // ink-3
    expect(toHex(light.primaryBg), '#21201c');
    expect(toHex(light.primaryFg), '#fdfdfc');
    expect(toHex(dark.panel), '#111110');
    expect(toHex(dark.overlay), '#191918');
    // Dark ground: ink-1 with OKLCH L - 0.04.
    final delta = rgbToOkLch(dark.panel).l - rgbToOkLch(dark.ground).l;
    expect(delta, closeTo(0.04, 0.01));
    // Primary hover = 93% bg / 7% fg in OKLab.
    expect(
      light.primaryHover,
      mixOkLab(light.primaryBg, light.primaryFg, 0.07),
    );
    // Amber text on solid is neutral ink-12, others white.
    expect(light.hues['warning']!.contrast, light.inkStep(12));
    expect(toHex(light.hues['success']!.contrast), '#ffffff');
  });
}
