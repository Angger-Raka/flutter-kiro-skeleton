// First token generator: design/tokens.yaml -> lib/core/theme/tokens.g.dart.
// A deliberate stand-in for `kit tokens` (Phase 2). Run from skeleton/:
//   dart run tool/generate_tokens.dart
import 'dart:io';

import 'src/knobs.dart';
import 'src/palette.dart';

/// Default input and output, relative to `skeleton/`.
const defaultYamlPath = 'design/tokens.yaml';

/// Default output file.
const defaultOutputPath = 'lib/core/theme/tokens.g.dart';

/// Runs the generator. Returns 0 on success and non-zero on any failure; on
/// failure [outputPath] is left unchanged.
Future<int> runGenerator({
  required String yamlPath,
  required String outputPath,
  required StringSink stdout,
}) async {
  final Knobs knobs;
  try {
    knobs = Knobs.parse(await File(yamlPath).readAsString());
  } on FileSystemException catch (e) {
    stdout.writeln('Cannot read $yamlPath: ${e.message}');
    return 2;
  } on KnobsException catch (e) {
    stdout.writeln('tokens: ${e.message}');
    return 1;
  }

  final rendered = _render(knobs);
  await _writeAtomically(outputPath, rendered);
  return 0;
}

String _render(Knobs knobs) {
  final lightInk = baseInk(knobs, dark: false);
  final darkInk = baseInk(knobs, dark: true);
  final light = buildPalette(knobs, dark: false, ink: lightInk);
  final dark = buildPalette(knobs, dark: true, ink: darkInk);

  return [
    '// GENERATED by tool/generate_tokens.dart from design/tokens.yaml.',
    '// Do not edit by hand.',
    '// language: tactile-design@30495a2',
    '// ignore_for_file: type=lint',
    '',
    "import 'package:flutter/painting.dart';",
    '',
    renderPalette(light, dark),
  ].join('\n');
}

/// Writes to a temp file next to [path], formats it, then renames over it, so
/// a failure never leaves a half-written output.
Future<void> _writeAtomically(String path, String content) async {
  final tmp = File('$path.tmp');
  await tmp.parent.create(recursive: true);
  await tmp.writeAsString(content);
  final fmt = await Process.run(Platform.resolvedExecutable, [
    'format',
    tmp.path,
  ]);
  if (fmt.exitCode != 0) {
    await tmp.delete();
    throw StateError('dart format failed: ${fmt.stderr}');
  }
  await tmp.rename(path);
}

Future<void> main() async {
  exitCode = await runGenerator(
    yamlPath: defaultYamlPath,
    outputPath: defaultOutputPath,
    stdout: stdout,
  );
}
