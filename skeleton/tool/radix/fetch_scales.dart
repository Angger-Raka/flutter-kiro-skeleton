// Fetches the Radix Colors scales used by the token generator and writes
// tool/radix/radix_scales.dart. Run from skeleton/:
//   dart run tool/radix/fetch_scales.dart
// No colour value is typed by hand; everything is parsed from upstream.
import 'dart:convert';
import 'dart:io';

const _commit = 'dbdb854';
const _scales = ['sand', 'slate', 'blue', 'green', 'red', 'amber'];
const _base = 'https://raw.githubusercontent.com/radix-ui/colors/$_commit/src';

Future<String> _download(String file) async {
  final client = HttpClient();
  try {
    final request = await client.getUrl(Uri.parse('$_base/$file'));
    final response = await request.close();
    if (response.statusCode != 200) {
      throw HttpException('HTTP ${response.statusCode}', uri: request.uri);
    }
    return await response.transform(utf8.decoder).join();
  } finally {
    client.close();
  }
}

/// Returns the values of `export const [name] = { ... };` in step order.
Map<int, String> _block(String source, String name) {
  final block = RegExp(
    'export const $name = \\{([^}]*)\\};',
  ).firstMatch(source);
  if (block == null) throw FormatException('Block $name not found');
  final out = <int, String>{};
  for (final m in RegExp(
    r'\w+?(\d+): "(#[0-9a-fA-F]+)"',
  ).allMatches(block.group(1)!)) {
    out[int.parse(m.group(1)!)] = m.group(2)!.toLowerCase();
  }
  return out;
}

String _list(Map<int, String> steps) {
  final values = [for (var i = 1; i <= 12; i++) steps[i]!];
  return '[${values.map((v) => "'$v'").join(', ')}]';
}

String _alpha(Map<int, String> steps) =>
    "{'a3': '${steps[3]}', 'a4': '${steps[4]}'}";

Future<void> main() async {
  final light = await _download('light.ts');
  final dark = await _download('dark.ts');
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/radix/fetch_scales.dart from')
    ..writeln('// radix-ui/colors@$_commit (src/light.ts, src/dark.ts), MIT.')
    ..writeln('// Do not edit by hand.')
    ..writeln()
    ..writeln(
      '/// One Radix colour scale: 12 steps plus alpha steps a3 and a4.',
    )
    ..writeln('class RadixScale {')
    ..writeln('  /// Creates a scale.')
    ..writeln('  const RadixScale({')
    ..writeln('    required this.name,')
    ..writeln('    required this.light,')
    ..writeln('    required this.dark,')
    ..writeln('    required this.lightAlpha,')
    ..writeln('    required this.darkAlpha,')
    ..writeln('  });')
    ..writeln()
    ..writeln('  /// Scale name, for example `sand`.')
    ..writeln('  final String name;')
    ..writeln()
    ..writeln('  /// 12 light values as `#rrggbb`; index 0 is step 1.')
    ..writeln('  final List<String> light;')
    ..writeln()
    ..writeln('  /// 12 dark values as `#rrggbb`; index 0 is step 1.')
    ..writeln('  final List<String> dark;')
    ..writeln()
    ..writeln('  /// Light alpha steps a3 and a4 as `#rrggbbaa`.')
    ..writeln('  final Map<String, String> lightAlpha;')
    ..writeln()
    ..writeln('  /// Dark alpha steps a3 and a4 as `#rrggbbaa`.')
    ..writeln('  final Map<String, String> darkAlpha;')
    ..writeln('}')
    ..writeln()
    ..writeln('/// The checked-in scales, keyed by name.')
    ..writeln('const radixScales = <String, RadixScale>{');
  for (final s in _scales) {
    out
      ..writeln("  '$s': RadixScale(")
      ..writeln("    name: '$s',")
      ..writeln('    light: ${_list(_block(light, s))},')
      ..writeln('    dark: ${_list(_block(dark, '${s}Dark'))},')
      ..writeln('    lightAlpha: ${_alpha(_block(light, '${s}A'))},')
      ..writeln('    darkAlpha: ${_alpha(_block(dark, '${s}DarkA'))},')
      ..writeln('  ),');
  }
  out.writeln('};');
  final target = File('tool/radix/radix_scales.dart');
  await target.writeAsString(out.toString());
  await Process.run(Platform.resolvedExecutable, ['format', target.path]);
  stdout.writeln('Wrote ${target.path}');
}
